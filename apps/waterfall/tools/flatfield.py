"""The receiver's own spectral shape, measured and written out as src/flat_tables.h.

Every capture carries the same shape about the LO: the analog filters' roll-off (-2.7 dB at
+-20 MHz at 80 MS/s), a broad bump around the LO and a few faint lines at fixed offsets. It
is the same at every tuning (within 0.2 to 0.4 dB from 1800 to 2800 MHz), cold or warm, and
nearly so at every gain; the app divides it out of each capture (f, $flat).

  flatfield.py measure -o cal.npz [--gains 0,10,...]
      the raw bins (before any correction) at 48 LOs from 1801 to 2788 MHz, at each of the
      three capture rates and each gain; about 11 s a rate and gain
  flatfield.py header cal.npz [more.npz ...] [-o src/flat_tables.h] [--png shape.png]
      each rate's shape in each gain set: the median over all the tunings (a real signal or
      a clock line sits at a fixed frequency, so it moves through the bins and drops out)

The tables are this board's; another board's filters may differ a little: measure it, write
the header and rebuild.
"""

import argparse
import sys
import time

# span (MHz) -> the rate it captures at; the order is the tables' (FLAT_RATES in main.c)
SPANS = {40: 80, 16: 40, 4: 16}
# 21 MHz apart: the board's clock harmonics (multiples of 4, 40 and 48 MHz) land in different
# bins at each LO and drop out of the median; on a round grid they stayed and were cut as shape
LOS = list(range(1801, 2800, 21))
GAIN_SETS = (35, 55)  # gain <= 35, <= 55, above (FLAT_GAIN_* in main.c)
BRIDGE_KHZ = 120  # lo_bridge() in main.c redraws these bins
MAX_BOOST_DB, MAX_CUT_DB = 8.0, 20.0
NFFT = 1024


def gain_set(gain):
    return sum(gain > g for g in GAIN_SETS)


def measure(link, gains, frames=6, frames_extra=4, out=print):
    """{"s<span>_g<gain>": (LOs, NFFT) mean dB, fftshifted, "s<span>_fs": Hz}."""
    import numpy as np
    from wf_serial import FRAME_BINS, bins_db

    res = {}
    link.command("$peak 1")
    for span in SPANS:
        link.command(f"$span {span}")
        for g in gains:
            link.command(f"$gain {g}")
            prof = np.full((len(LOS), NFFT), np.nan, np.float32)
            t0 = time.time()
            for i, lo in enumerate(LOS):
                link.command(f"$lo {lo}")
                link.command(f"$bins {frames + frames_extra}")
                rows = []
                for f in link.frames(FRAME_BINS, frames + frames_extra):
                    if f.lo_khz == lo * 1000 and f.gain == g:  # not one from before the retune
                        rows.append(bins_db(f))
                        res[f"s{span}_fs"] = f.fs_hz
                if rows:
                    p = 10 ** (np.vstack(rows[-frames:]) / 10)
                    prof[i] = 10 * np.log10(np.mean(p, axis=0))
            res[f"s{span}_g{g}"] = prof
            out(f"span {span} gain {g}: {time.time() - t0:.0f} s")
    return res


def shapes(datasets):
    """{(rate MS/s, gain set): (correction dB fftshifted, rows)} from measure()'s dicts."""
    import numpy as np

    rows = {}
    fs = {}
    for d in datasets:
        for key in d:
            if not key.startswith("s") or "_g" not in key:
                continue
            span, g = (int(v) for v in key[1:].split("_g"))
            fs[span] = float(d[f"s{span}_fs"])
            rows.setdefault((SPANS[span], gain_set(g)), []).append(np.asarray(d[key]))
    out = {}
    for (rate, gs), blocks in rows.items():
        span = next(s for s, r in SPANS.items() if r == rate)
        f_khz = (np.arange(NFFT) - NFFT // 2) * fs[span] / NFFT / 1e3
        mid = np.abs(f_khz) < fs[span] / 4e3
        p = np.vstack(blocks)
        p = p[~np.isnan(p).any(axis=1)]
        # each tuning on its own floor: a low percentile, past any signal in it
        p = p - np.percentile(p[:, mid], 20, axis=1, keepdims=True)
        shape = np.median(p, axis=0)
        corr = np.median(shape[mid]) - shape
        corr = np.clip(corr, -MAX_CUT_DB, MAX_BOOST_DB)
        corr[np.abs(f_khz) <= BRIDGE_KHZ] = 0.0  # the LO line: lo_bridge()'s
        out[(rate, gs)] = (corr, len(p))
    return out


def header(tables, sources):
    """C: flat_tab[rate][gain set][bin], power factors in the FFT's own order (DC first)."""
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/*",
        " * Generated by tools/flatfield.py from " + ", ".join(sources) + ": do not edit.",
        " * The receiver's shape about the LO divided out (main.c, flat_apply()): power",
        " * factors per FFT bin, DC first, for 80, 40 and 16 MS/s and gains <= "
        f"{GAIN_SETS[0]}, <= {GAIN_SETS[1]} and above.",
        " */",
        "",
        f"#define FLAT_GAIN_LOW {GAIN_SETS[0]}",
        f"#define FLAT_GAIN_MID {GAIN_SETS[1]}",
        "",
        f"static const float flat_tab[3][3][{NFFT}] = {{",
    ]
    for rate in (80, 40, 16):
        lines.append(f"\t{{ /* {rate} MS/s */")
        for gs in range(3):
            corr, n = tables.get((rate, gs), (None, 0))
            if corr is None:
                corr, n = tables[(rate, 1)]
            nat = [corr[(k + NFFT // 2) % NFFT] for k in range(NFFT)]
            lines.append(f"\t\t{{ /* gain set {gs}, {n} captures */")
            for i in range(0, NFFT, 8):
                vals = ", ".join(f"{10 ** (c / 10):.4f}f" for c in nat[i:i + 8])
                lines.append(f"\t\t\t{vals},")
            lines.append("\t\t},")
        lines.append("\t},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def save_png(path, tables):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np

    fig, ax = plt.subplots(3, 1, figsize=(10, 9))
    for row, rate in enumerate((80, 40, 16)):
        f = (np.arange(NFFT) - NFFT // 2) * rate / NFFT
        for gs in range(3):
            if (rate, gs) in tables:
                ax[row].plot(f, -tables[(rate, gs)][0], lw=0.7, label=f"gain set {gs}")
        ax[row].set_title(f"{rate} MS/s: the shape taken out (dB)")
        ax[row].grid()
        ax[row].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=80)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("measure")
    p.add_argument("--port")
    p.add_argument("--gains", default="0,10,20,30,42,50,60,70,82")
    p.add_argument("-o", required=True, help=".npz")
    p = sub.add_parser("header")
    p.add_argument("npz", nargs="+")
    p.add_argument("-o", default="-", help="the header (default: stdout)")
    p.add_argument("--png")
    args = ap.parse_args()

    import numpy as np

    if args.cmd == "measure":
        import wf_serial

        link = wf_serial.Link(args.port or wf_serial.find_port())
        try:
            status = link.sync()
            link.pause_screen()
            res = measure(link, [int(g) for g in args.gains.split(",")],
                          out=lambda s: print(s, file=sys.stderr))
        finally:
            # back as found
            st = dict(zip(status.split()[1::2], status.split()[2::2]))
            gain = st["gain"] if int(st["gain"]) >= 0 else "auto"
            for line in (f"$peak {st['peak']}", f"$gain {gain}",
                         f"$span {int(st['span']) // 1000}", f"$tune {st['view']}"):
                try:
                    link.command(line)
                except TimeoutError:
                    pass
            link.close()
        np.savez(args.o, los=np.array(LOS), **res)
        return

    tables = shapes([np.load(f) for f in args.npz])
    text = header(tables, [f.split("/")[-1] for f in args.npz])
    if args.o == "-":
        sys.stdout.write(text)
    else:
        with open(args.o, "w") as f:
            f.write(text)
    if args.png:
        save_png(args.png, tables)


if __name__ == "__main__":
    main()
